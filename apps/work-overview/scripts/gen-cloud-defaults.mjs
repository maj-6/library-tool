/**
 * Generate electron/cloudDefaults.generated.ts from tools/cloud_defaults.py.
 *
 * The Python module is the single source of truth for which cloud this app
 * talks to (see its docstring: PUBLIC identifiers only). Copying the values by
 * hand would let this app drift onto a different project than the rest of the
 * suite, so they are derived at build time and the result is committed.
 */
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const here = path.dirname(fileURLToPath(import.meta.url))
const appDir = path.resolve(here, '..')
const repoRoot = path.resolve(appDir, '..', '..')
const source = path.join(repoRoot, 'tools', 'cloud_defaults.py')

const text = fs.readFileSync(source, 'utf8')

/** Read `NAME = "..."`, including a parenthesised run of adjacent literals. */
function readPyString(name) {
  const simple = text.match(new RegExp(`^${name}\\s*=\\s*"([^"]*)"`, 'm'))
  if (simple) return simple[1]
  const joined = text.match(new RegExp(`^${name}\\s*=\\s*\\(([\\s\\S]*?)\\)`, 'm'))
  if (!joined) throw new Error(`${name} not found in ${source}`)
  const parts = [...joined[1].matchAll(/"([^"]*)"/g)].map((m) => m[1])
  if (!parts.length) throw new Error(`${name} has no string parts in ${source}`)
  return parts.join('')
}

const url = readPyString('SUPABASE_URL')
const anonKey = readPyString('SUPABASE_ANON_KEY')

// Refuse to bake a privileged key even if cloud_defaults.py is ever wrong:
// a service_role key in a shipped renderer bundle would be a total compromise.
const payload = JSON.parse(Buffer.from(anonKey.split('.')[1] ?? '', 'base64url').toString('utf8'))
if (payload.role !== 'anon') {
  throw new Error(`refusing to generate: SUPABASE_ANON_KEY role is ${payload.role}, expected anon`)
}

const out = `// GENERATED by scripts/gen-cloud-defaults.mjs from tools/cloud_defaults.py.
// Do not edit. Run \`npm run build\` (or node scripts/gen-cloud-defaults.mjs) to refresh.
// Public identifiers only — row-level security is what protects the project.
export const SUPABASE_URL = ${JSON.stringify(url)}
export const SUPABASE_ANON_KEY = ${JSON.stringify(anonKey)}
`

const target = path.join(appDir, 'electron', 'cloudDefaults.generated.ts')
const existing = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : ''
if (existing !== out) {
  fs.writeFileSync(target, out, 'utf8')
  console.log(`wrote ${path.relative(repoRoot, target)}`)
} else {
  console.log('cloud defaults unchanged')
}
